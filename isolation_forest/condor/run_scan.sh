#!/bin/bash
# run_scan.sh — worker-node entry point for the training-fraction scan.
#
# One script, three phases (selected by the first argument), so the shared
# environment setup lives in a single place:
#
#   train   $1=BASE_TAG $2=TRAINFRAC
#           Train ONE IsolationForest on a fraction (TRAINFRAC) of good_list
#           (config default: good_run_list_TRAINING.txt) and save it under
#           models/<BASE_TAG>/.  No apply/evaluate/report/plots.
#
#   apply   $1=BASE_TAG $2=RUN_GROUP   (RUN_GROUP = run numbers joined by '+')
#           Load the model <BASE_TAG> (--skip-train) and apply it to
#           every run in RUN_GROUP via --apply-specific-run, writing one
#           logs/<SCAN_SUBDIR>/<tag>_run<N>.csv per run.  The SAME model is used
#           for every run and every batch — nothing is retrained here.
#
#   combine $1=BASE_TAG
#           Merge all per-run CSVs for the model into one log, then evaluate →
#           report → plots for that model.
#
# Submitted by submit_scan_{train,apply,combine}.sub, ordered by condor/scan.dag
# (train → apply → combine).  All parameter files are generated by batch_submit.sh.
#
# Tag handling (see src/pipeline.py): pipeline.py only auto-suffixes the tag with
# "_<QUALITY>" when --train-goodRunList is what actually trained the model
# (guarded by "not args.skip_train").  The train phase here uses plain
# --good-list/--fraction, so no suffix is ever added — the model saves to
# models/<BASE_TAG>/ exactly, and apply/combine use MODEL_TAG=BASE_TAG unchanged
# to resolve the same directory.  The APPLY phase still passes
# --train-goodRunList/-quality "$QUALITY" for one reason only: it makes
# --apply-specific-run resolve the run's subruns by scanning the EOS slab
# directory directly, so any run can be targeted regardless of its quality flags.
#
# The COMBINE phase deliberately does NOT pass it: in pipeline.py's evaluate step
# that flag also switches the ground truth from the good_list text file to the
# JSON catalogue, which produced known_good = 0 and therefore no false-positive
# rate.  See the comment on the combine phase below.

set -euo pipefail

# ── Constants shared by all phases ────────────────────────────────────────────
CONFIG="configs/config.yaml"
QUALITY="Tight"                    # training/ground-truth quality level
SCAN_SUBDIR="scan_train20_apply100" # reports/<SUBDIR>, plots/<SUBDIR> (small, stay on AFS)
APPLY_FRAC="1.0"                   # --apply-specific-run-fraction (1.0 = all subruns)

# Feature variant.  "digi only" in the sweep-comparison scripts means BOTH trigger
# and LVDS features off — VARIANT_META[(False, False)] in
# _auxiliar_scripts/compare_sweep_*.py.  config.yaml on its own sets
# use_trigger: false but use_lvds: true, which is the "+ LVDS counts" variant, so
# --no-trigger-LVDS is REQUIRED to reproduce the digi-only sweep points.
# --no-trigger / --no-trigger-config only restate the config defaults, but keeping
# them here makes the variant explicit in the model tag and the job logs.
#
# Every phase must pass the SAME flags: pipeline.py builds the model-tag suffix
# (_noTrigger_noLVDS_ignoreTriggerConfig) from the resolved feature flags, so a
# mismatch between train and apply would send apply looking for a model directory
# that was never written.
FEATURE_FLAGS=(--no-trigger --no-trigger-LVDS --no-trigger-config)

# DAQ-config variant toggle — kept SEPARATE from the apply-fraction test.
# The digi-only model keeps the DAQ-config feature ON (config
# includeConfigInfo_DAQ: true → channel.triggerThreshold), which is the baseline
# for the 100%-apply comparison against the group's 3.58%.  Set
# STRIP_DAQ_CONFIG=true to ALSO drop the DAQ-config feature: this appends
# --no-daq-config, which trains a SEPARATE model (tag gains _ignoreDAQConfig) and
# writes to a SEPARATE output subdir (<SUBDIR>_noDAQ), so DAQ-on and DAQ-off
# results never mix.  Run the DAQ-on test first; flip this only for the follow-up.
STRIP_DAQ_CONFIG=false
if [ "$STRIP_DAQ_CONFIG" = true ]; then
    FEATURE_FLAGS+=(--no-daq-config)
    SCAN_SUBDIR="${SCAN_SUBDIR}_noDAQ"
fi
INSTALLATION_PATH="/afs/cern.ch/user/l/lbailloe/private/autoDQM/isolation_forest"
# Bulk scan CSVs live on EOS, not AFS: per-run outputs are ~1 GB per fraction
# and the combine step writes an equal-sized merged log per fraction (~9 GB
# working set for 5 fractions) — more than any AFS home quota.  EOS is mounted
# on the batch workers, and these are large sequential writes (the
# fuse-friendly case).
SCAN_LOGS_DIR="/eos/user/l/lbailloe/autoDQM_scan/logs/${SCAN_SUBDIR}"

PHASE=${1:?Usage: run_scan.sh <train|apply|combine> ...}
shift

cd "${INSTALLATION_PATH}"

# ── Make pip --user packages visible on worker nodes (see run_pipeline.sh) ────
PYVER=$(python3 -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')")
export PYTHONUSERBASE="${HOME}/.local"
export PATH="${HOME}/.local/bin:${PATH}"
export PYTHONPATH="${HOME}/.local/lib/python${PYVER}/site-packages:${INSTALLATION_PATH}:${PYTHONPATH:-}"

python3 -c "import pandas, sklearn, numpy, scipy, watchdog" || {
    echo "ERROR: required packages not found." >&2
    echo "Run 'bash setup.sh' on lxplus before submitting condor jobs." >&2
    exit 1
}

# EOS must be reachable and the scan output dir must exist before any phase
# writes to it; failing here (exit 1) is deliberate — it is a systemic
# problem, unlike a single run with missing data.
mkdir -p "${SCAN_LOGS_DIR}" || {
    echo "ERROR: cannot create scan logs dir on EOS: ${SCAN_LOGS_DIR}" >&2
    exit 1
}

echo "============================================================"
echo "  autoDQM scan — phase: $PHASE"
echo "  Host : $(hostname)"
echo "  Start: $(date -u)"
echo "============================================================"

case "$PHASE" in
    # ── Phase 1: train one model for one fraction ────────────────────────────
    train)
        BASE_TAG=${1:?Usage: run_scan.sh train <base_tag> <train_fraction>}
        TRAINFRAC=${2:?Usage: run_scan.sh train <base_tag> <train_fraction>}
        echo "  Base tag   : $BASE_TAG   (model dir: models/${BASE_TAG}/)"
        echo "  Train frac : $TRAINFRAC  (of good_list)"
        echo ""
        python3 -m src.pipeline \
            --config "$CONFIG" \
            --model-tag "$BASE_TAG" \
            --fraction "$TRAINFRAC" \
            "${FEATURE_FLAGS[@]}" \
            --skip-apply --skip-evaluate --skip-report --skip-all-plots
        ;;

    # ── Phase 2: apply that model to a group of runs (no retraining) ─────────
    apply)
        BASE_TAG=${1:?Usage: run_scan.sh apply <base_tag> <run_group>}
        RUN_GROUP=${2:?Usage: run_scan.sh apply <base_tag> <run_group>}
        MODEL_TAG="${BASE_TAG}"          # matches the unsuffixed tag written by the train phase
        IFS='+' read -ra RUNS <<< "$RUN_GROUP"
        echo "  Model tag  : $MODEL_TAG"
        echo "  Runs       : ${RUNS[*]}  (${#RUNS[@]} run(s), apply-fraction ${APPLY_FRAC})"
        echo ""
        n_ok=0
        n_fail=0
        for RUN in "${RUNS[@]}"; do
            echo "--- Run $RUN ---"
            # Without --train-goodRunList, --apply-specific-run resolves the
            # run's files by filtering the config apply_list — the same list
            # batch_submit.sh drew the run numbers from.
            if python3 -m src.pipeline \
                    --config "$CONFIG" \
                    --model-tag "$MODEL_TAG" \
                    --skip-train \
                    --apply-specific-run "$RUN" \
                    --apply-specific-run-fraction "$APPLY_FRAC" \
                    "${FEATURE_FLAGS[@]}" \
                    --logs-dir "${SCAN_LOGS_DIR}"; then
                n_ok=$((n_ok + 1))
            else
                echo "WARNING: run $RUN failed (exit $?) — continuing" >&2
                n_fail=$((n_fail + 1))
            fi
        done
        echo ""
        echo "  Apply summary: OK=$n_ok  FAILED=$n_fail  of ${#RUNS[@]}"
        # Never exit non-zero for per-run failures: all apply jobs are procs of
        # ONE DAG node, and DAGMan fails the node — and aborts the whole DAG —
        # if ANY proc exits non-zero.  A single run with no files on EOS (e.g.
        # run 1617) must not kill the scan; the combine phase merges whatever
        # CSVs exist.  Systemic problems are still caught: the dependency check
        # above exits 1 before this phase, and combine fails if no CSVs landed.
        ;;

    # ── Phase 3: combine per-run outputs, then evaluate/report/plots ─────────
    combine)
        BASE_TAG=${1:?Usage: run_scan.sh combine <base_tag>}
        MODEL_TAG="${BASE_TAG}"
        echo "  Model tag  : $MODEL_TAG"
        echo ""
        echo "  --- Pass 1: combine per-run outputs ---"
        python3 -m src.pipeline \
            --config "$CONFIG" \
            --model-tag "$MODEL_TAG" \
            --skip-train \
            "${FEATURE_FLAGS[@]}" \
            --logs-dir "${SCAN_LOGS_DIR}" \
            --combine-specific-run-outputs '*'

        echo ""
        echo "  --- Pass 2: evaluate (report + plots) ---"
        # Ground truth: TEXT LIST, not the catalogue.  pipeline.py branches on
        # --train-goodRunList here (STEP 3): with it, known-good is defined by
        # goodRunsListSlab.json at --train-goodRunList-quality; without it, by
        # cfg["good_list"] (good_run_list_TRAINING.txt).
        #
        # Catalogue mode is wrong for this scan: NO subrun in the applied range
        # passes Tight, so every previous eval_summary.txt came out with
        # known_good = 0 and printed no "False Positive (alert)" line at all —
        # the only rate shown was "Possible TP (alert)" on not-certified subruns,
        # which counts alerts on BAD data and is not a false-positive rate.
        # Text-list mode restores the known-good bucket, so the FP rate is
        # comparable with collaborators who evaluate against the same list.
        # Runs outside the list simply fall into "unknown" and do not affect it.
        python3 -m src.pipeline \
            --config "$CONFIG" \
            --model-tag "$MODEL_TAG" \
            --skip-train --skip-apply \
            "${FEATURE_FLAGS[@]}" \
            --logs-dir    "${SCAN_LOGS_DIR}" \
            --reports-dir "reports/${SCAN_SUBDIR}" \
            --plots-dir   "plots/${SCAN_SUBDIR}"
        ;;

    *)
        echo "ERROR: unknown phase '$PHASE' (expected train|apply|combine)" >&2
        exit 1
        ;;
esac

echo ""
echo "============================================================"
echo "  Done: phase $PHASE  $(date -u)"
echo "============================================================"
